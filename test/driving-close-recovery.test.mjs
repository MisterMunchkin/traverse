import './support/isolated-approval-state.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {drivingFixture, packageRoot} from './support/driving-fixture.mjs';
const cli = path.join(packageRoot, 'bin/traverse.mjs');

test('PATH mismatch gives a literal close command while hash changes still refuse cleanup', t => {
  const f = drivingFixture(t), bin = path.join(f.root, 'bin'); fs.mkdirSync(bin);
  const original = path.join(f.root, "runner ' $(touch SHOULD_NOT_EXIST)"); fs.renameSync(f.executable, original);
  const bytes = fs.readFileSync(original);
  fs.copyFileSync(original, path.join(bin, 'agent-device'));
  const env = {...process.env, PATH: bin + path.delimiter + process.env.PATH, HOME: path.join(f.root, 'home'), NO_COLOR: '1'};
  const run = (args, code = 0) => {
    const r = spawnSync(process.execPath, [cli, ...args], {cwd: f.project, env, encoding: 'utf8', timeout: 30000});
    assert.equal(r.status, code, r.stdout + r.stderr); assert.equal(r.signal, null); return r;
  };
  run(['init', '--json']);
  const open = name => run(['session', 'open', '--session', name, '--platform', 'web', '--app', 'http://fixture', '--agent-device', original, '--json']);
  const first = JSON.parse(open('owned').stdout), other = JSON.parse(open('other').stdout);
  const state = () => JSON.parse(fs.readFileSync(f.state));
  const calls = () => fs.readFileSync(f.log, 'utf8').trim().split('\n').map(JSON.parse);
  const before = calls().length;
  const args = ['session', 'close', '--session', 'owned'];
  const json = run([...args, '--json'], 1); assert.equal(json.stderr, '');
  const error = JSON.parse(json.stdout); assert.equal(error.exitCode, 1);
  assert.match(error.error, /selected.*runner.*differs/i);
  const command = error.error.split('Retry with: ')[1]; assert.ok(command);
  const human = run(args, 1); assert.equal(human.stdout, ''); assert.ok(human.stderr.includes(command));
  assert.equal(calls().length, before); assert.equal(state()[first.runnerSession].active, true);
  fs.appendFileSync(original, '\n// changed bytes');
  const changed = run([...args, '--agent-device', original, '--json'], 1);
  assert.match(JSON.parse(changed.stdout).error, /restore its recorded bytes/);
  assert.equal(calls().length, before); assert.equal(state()[first.runnerSession].active, true);
  fs.writeFileSync(original, bytes);
  const closed = spawnSync('/bin/sh', ['-c', command], {cwd: f.root, env, encoding: 'utf8', timeout: 30000});
  assert.equal(closed.status, 0, closed.stdout + closed.stderr);
  assert.equal(state()[first.runnerSession].active, false);
  assert.equal(state()[other.runnerSession].active, true);
  assert.equal(fs.existsSync(path.join(f.root, 'SHOULD_NOT_EXIST')), false);
  const closeCalls = calls().filter(c => c.args[0] === 'close');
  assert.equal(closeCalls.length, 1); assert.ok(closeCalls[0].args.includes(first.runnerSession));
  run(['session', 'close', '--session', 'other', '--agent-device', original, '--json']);
});
